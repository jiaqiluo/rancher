// plainYAMLArg matches values that a YAML plain scalar carries without a change.
var plainYAMLArg = regexp.MustCompile(`^[A-Za-z0-9_./@=,+-][A-Za-z0-9_./:@=,+-]*$`)

// yamlString returns s as a YAML double quoted scalar. The values come from cluster and user objects,
// so a quote or a line break in a value must not end the scalar and add YAML keys.
// A JSON string is a valid YAML double quoted scalar.
func yamlString(s string) (string, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		return "", err
	}
	return strings.TrimSuffix(b.String(), "\n"), nil
}

// yamlArg returns prefix+value as a YAML scalar for a list item. A value that is plain stays unquoted.
// Any other value is written as a double quoted scalar.
func yamlArg(prefix, value string) (string, error) {
	arg := prefix + value
	if plainYAMLArg.MatchString(arg) && !strings.HasSuffix(arg, ":") {
		return arg, nil
	}
	return yamlString(arg)
}

var funcs = template.FuncMap{
	"yamlString": yamlString,
	"yamlArg":    yamlArg,
}

